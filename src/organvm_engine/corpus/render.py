"""Render the corpus knowledge graph as navigable markdown indices.

Step 4 of the corpus pipeline (IRF-SYS-104, issue #81): the scanner builds
the graph, the renderer publishes it as six deterministic markdown files
(``organvm corpus render``). Every renderer is a pure function of a
``CorpusGraph`` and returns markdown text; output is sorted throughout so
re-renders diff cleanly (no timestamps, no filesystem order).

Bridge note: the scanner emits no concept-to-concept edges, so a bridge
cannot be read off a single edge. ``render_cross_corpus_bridges`` therefore
reports the two bridge signals the graph actually carries: concepts whose
``trunks`` span more than one trunk, and pairs of concepts in different
trunks that share a transcript, spec, repo or document node.
"""

from __future__ import annotations

from collections import Counter
from pathlib import Path

from organvm_engine.corpus.graph import CorpusGraph, GraphNode

RENDER_FILES: tuple[str, ...] = (
    "concept-index.md",
    "provenance-map.md",
    "spec-coverage.md",
    "tag-analysis.md",
    "cross-corpus-bridges.md",
    "gaps.md",
)

# Under-referenced areas named in issue #81. A keyword matches a concept
# when it appears in the concept id or title (case-insensitive).
UNDER_REFERENCED: tuple[tuple[str, str], ...] = (
    ("SVSE", "svse"),
    ("Faculty", "faculty"),
    ("Commission", "commission"),
    ("Defense governance", "defense"),
)


def _plural(count: int, singular: str, plural: str | None = None) -> str:
    """Render a count with the right noun form ("1 concept", "2 concepts")."""
    if count == 1:
        return f"1 {singular}"
    return f"{count} {plural or singular + 's'}"


def _cell(value: object) -> str:
    """Make a value safe for a markdown table cell."""
    return " ".join(str(value).split()).replace("|", "\\|")


def _concept_id(uid: str) -> str:
    return uid.removeprefix("concept:")


def _sorted_concepts(graph: CorpusGraph) -> list[GraphNode]:
    return sorted(graph.nodes_by_type("concept"), key=lambda n: n.uid)


def _trunks(node: GraphNode) -> list[str]:
    trunks = node.metadata.get("trunks", [])
    if isinstance(trunks, str):
        return [trunks]
    return [str(t) for t in trunks]


def _description(node: GraphNode) -> str:
    return str(node.metadata.get("description", ""))


def _primary_source(node: GraphNode) -> str:
    return str(
        node.metadata.get("primary_source", node.metadata.get("source", "")),
    )


def _header(title: str, intro: str) -> str:
    return (
        f"# {title}\n\n{intro}\n\n"
        "Generated by `organvm corpus render` from the corpus knowledge graph; "
        "re-render to refresh.\n\n"
    )


def render_concept_index(graph: CorpusGraph) -> str:
    """Every concept node: id, title, description, trunks, primary source.

    Why a table: the index is the lookup surface — one row per concept,
    sorted by concept id, so a reader finds a concept without scanning
    the graph JSON.
    """
    concepts = _sorted_concepts(graph)
    out = [_header(
        "Concept index",
        f"{_plural(len(concepts), 'concept')} in the corpus knowledge graph.",
    )]
    if not concepts:
        out.append("No concepts in this graph.\n")
        return "".join(out)
    out.append("| Concept | Title | Description | Trunks | Primary source |\n")
    out.append("| --- | --- | --- | --- | --- |\n")
    for node in concepts:
        out.append(
            f"| {_cell(_concept_id(node.uid))} | {_cell(node.title)} | "
            f"{_cell(_description(node))} | "
            f"{_cell(', '.join(_trunks(node)))} | "
            f"{_cell(_primary_source(node))} |\n",
        )
    return "".join(out)


def render_provenance_map(graph: CorpusGraph) -> str:
    """Per concept, its DEFINES source and EXTRACTED_FROM transcript chain.

    Why trace_concept: it is the graph's own provenance query (definitions,
    referencing documents, implementing repos), so the map cannot drift
    from what the CLI's ``trace`` command reports for the same concept.
    """
    concepts = _sorted_concepts(graph)
    out = [_header(
        "Provenance map",
        f"Provenance chain for each of the {_plural(len(concepts), 'concept')}.",
    )]
    if not concepts:
        out.append("No concepts in this graph.\n")
        return "".join(out)
    for node in concepts:
        concept_id = _concept_id(node.uid)
        trace = graph.trace_concept(concept_id)
        out.append(f"## {concept_id}\n\n")
        out.append(f"{_cell(trace.get('title', node.title))}\n\n")
        definitions = trace.get("definitions", [])
        if definitions:
            out.append("Defined by:\n\n")
            for d in definitions:
                out.append(
                    f"- [{_cell(d['type'])}] {_cell(d['title'])}"
                    f" (`{_cell(d['uid'])}`)\n",
                )
            out.append("\n")
        else:
            out.append("Defined by: — none recorded.\n\n")
        documents = trace.get("documents", [])
        if documents:
            out.append("Referenced in:\n\n")
            for d in documents:
                out.append(
                    f"- [{_cell(d['type'])}] {_cell(d['title'])}"
                    f" (`{_cell(d['uid'])}`)\n",
                )
            out.append("\n")
        else:
            out.append("Referenced in: — none recorded.\n\n")
        implementations = trace.get("implementations", [])
        if implementations:
            out.append(
                f"Implemented by ({trace.get('implementation_count', 0)} repos):\n\n",
            )
            for impl in implementations:
                organ = f" [{_cell(impl['organ'])}]" if impl.get("organ") else ""
                aspect = (
                    f" — {_cell(impl['aspect'])}" if impl.get("aspect") else ""
                )
                out.append(f"- {_cell(impl['repo'])}{organ}{aspect}\n")
            out.append("\n")
        else:
            out.append("[GAP] No implementations found.\n\n")
        organs = trace.get("organ_spread", [])
        if organs:
            out.append(f"Organ spread: {', '.join(_cell(o) for o in organs)}.\n\n")
    return "".join(out)


def render_spec_coverage(graph: CorpusGraph) -> str:
    """Per concept, implementation depth and fragility.

    Why coverage_depth: it is the graph's own fragility ranking (fewest
    implementations first), so the index and the CLI's ``coverage``
    command agree on which concepts are fragile.
    """
    depth = graph.coverage_depth()
    fragile = [d for d in depth if d["fragile"]]
    robust = [d for d in depth if not d["fragile"]]
    out = [_header(
        "SPEC coverage",
        f"{len(depth)} concepts: {len(fragile)} fragile (≤1 implementation), "
        f"{len(robust)} robust (≥2 implementations).",
    )]
    if not depth:
        out.append("No concepts in this graph.\n")
        return "".join(out)
    out.append(
        "| Concept | Implementations | Repos | Organs | Fragile |\n",
    )
    out.append("| --- | --- | --- | --- | --- |\n")
    for d in depth:
        out.append(
            f"| {_cell(d['concept'])} | {d['implementations']} | "
            f"{_cell(', '.join(d['repos']))} | "
            f"{_cell(', '.join(d['organs']))} | "
            f"{'yes' if d['fragile'] else 'no'} |\n",
        )
    return "".join(out)


def render_tag_analysis(graph: CorpusGraph) -> str:
    """Concept counts by trunk and document counts by tag.

    Why two tables: trunks live on concept nodes (``trunks`` metadata) and
    tags live on document nodes (``tags`` metadata) — they are different
    vocabularies, so merging them into one count would conflate the two.
    A concept with several trunks counts once per trunk; a document with
    several tags counts once per tag.
    """
    concepts = _sorted_concepts(graph)
    trunk_counts: Counter[str] = Counter()
    for node in concepts:
        trunks = _trunks(node)
        if trunks:
            trunk_counts.update(trunks)
        else:
            trunk_counts["(unassigned)"] += 1
    documents = graph.nodes_by_type("document")
    tag_counts: Counter[str] = Counter()
    for node in documents:
        tags = node.metadata.get("tags", [])
        if isinstance(tags, str):
            tags = [tags]
        tags = [str(t) for t in tags]
        if tags:
            tag_counts.update(tags)
        else:
            tag_counts["(untagged)"] += 1
    out = [_header(
        "Tag analysis",
        f"{_plural(len(concepts), 'concept')} across "
        f"{_plural(len(trunk_counts), 'trunk')}; "
        f"{_plural(len(documents), 'document')} across "
        f"{_plural(len(tag_counts), 'tag')}.",
    )]
    out.append("## Concepts by trunk\n\n")
    out.append("| Trunk | Concepts |\n| --- | --- |\n")
    for trunk, count in sorted(trunk_counts.items()):
        out.append(f"| {_cell(trunk)} | {count} |\n")
    out.append("\n## Documents by tag\n\n")
    out.append("| Tag | Documents |\n| --- | --- |\n")
    for tag, count in sorted(tag_counts.items()):
        out.append(f"| {_cell(tag)} | {count} |\n")
    return "".join(out)


def _adjacent_concepts(graph: CorpusGraph, uid: str) -> list[GraphNode]:
    """Concepts directly connected to a node, in either direction."""
    found: dict[str, GraphNode] = {}
    for edge in graph.edges:
        other: str | None = None
        if edge.source == uid and edge.target.startswith("concept:"):
            other = edge.target
        elif edge.target == uid and edge.source.startswith("concept:"):
            other = edge.source
        if other is not None:
            node = graph.get_node(other)
            if node is not None:
                found[other] = node
    return [found[key] for key in sorted(found)]


def render_cross_corpus_bridges(graph: CorpusGraph) -> str:
    """Edges whose endpoints sit in different corpora/trunks.

    Why this shape: the scanner emits no concept-to-concept edges, so the
    bridges the graph carries are (a) concepts whose ``trunks`` span more
    than one trunk — the AMMOI / Alpha-Omega / Formation Protocol /
    SPEC-notation strong connections the issue names — and (b) pairs of
    concepts in different trunks that share a transcript, spec, repo or
    document node. Both sections are sorted so re-renders diff cleanly.
    """
    concepts = _sorted_concepts(graph)
    multi_trunk = [n for n in concepts if len(set(_trunks(n))) > 1]
    out = [_header(
        "Cross-corpus bridges",
        f"{len(multi_trunk)} multi-trunk concepts in this graph.",
    )]
    out.append("## Multi-trunk concepts\n\n")
    if multi_trunk:
        out.append(
            "| Concept | Trunks | Definitions | Implementations | Organ spread |\n",
        )
        out.append("| --- | --- | --- | --- | --- |\n")
        for node in multi_trunk:
            concept_id = _concept_id(node.uid)
            trace = graph.trace_concept(concept_id)
            out.append(
                f"| {_cell(concept_id)} | "
                f"{_cell(', '.join(sorted(set(_trunks(node)))))} | "
                f"{len(trace.get('definitions', []))} | "
                f"{trace.get('implementation_count', 0)} | "
                f"{_cell(', '.join(trace.get('organ_spread', [])))} |\n",
            )
    else:
        out.append("No multi-trunk concepts in this graph.\n")
    out.append("\n## Concept pairs bridged by a shared node\n\n")
    pairs: dict[tuple[str, str], list[str]] = {}
    for node in sorted(graph.nodes.values(), key=lambda n: n.uid):
        if node.node_type == "concept":
            continue
        adjacent = _adjacent_concepts(graph, node.uid)
        for i, first in enumerate(adjacent):
            for second in adjacent[i + 1:]:
                first_trunks = set(_trunks(first))
                second_trunks = set(_trunks(second))
                if not first_trunks or not second_trunks:
                    continue
                if first_trunks == second_trunks:
                    continue
                first_id, second_id = sorted((
                    _concept_id(first.uid),
                    _concept_id(second.uid),
                ))
                key: tuple[str, str] = (first_id, second_id)
                pairs.setdefault(key, []).append(
                    f"{node.node_type} `{node.uid}`",
                )
    if pairs:
        out.append("| Concept A | Concept B | Shared node |\n")
        out.append("| --- | --- | --- |\n")
        for (first, second), shared in sorted(pairs.items()):
            out.append(
                f"| {_cell(first)} | {_cell(second)} | "
                f"{_cell(', '.join(sorted(set(shared))))} |\n",
            )
    else:
        out.append("No cross-trunk concept pairs in this graph.\n")
    return "".join(out)


def render_gaps(graph: CorpusGraph) -> str:
    """Orphan concepts plus the under-referenced areas issue #81 names.

    Why the two sections differ: an orphan concept is a gap the graph
    proves (no IMPLEMENTS edge targets it). A named area (SVSE, Faculty,
    Commission, Defense governance) is a gap only where the graph
    confirms it — a name absent from the graph is reported as absent,
    not as a confirmed gap, because absence from the graph is not proof
    of absence from the corpus.
    """
    orphans = sorted(
        graph.concepts_without_implementation(), key=lambda n: n.uid,
    )
    out = [_header(
        "Gaps",
        f"{_plural(len(orphans), 'concept')} without implementation "
        "in this graph.",
    )]
    out.append("## Orphan concepts\n\n")
    if orphans:
        for node in orphans:
            description = _description(node)
            detail = f" — {_cell(description)}" if description else ""
            source = _primary_source(node)
            where = f" (primary source: {_cell(source)})" if source else ""
            out.append(
                f"- `{_cell(_concept_id(node.uid))}` — "
                f"{_cell(node.title)}{detail}{where}\n",
            )
    else:
        out.append("No orphan concepts: every concept has an implementation.\n")
    out.append("\n## Under-referenced areas named in #81\n\n")
    implemented = {
        e.target for e in graph.edges if e.edge_type == "IMPLEMENTS"
    }
    for label, keyword in UNDER_REFERENCED:
        matches = [
            n for n in _sorted_concepts(graph)
            if keyword in _concept_id(n.uid).lower()
            or keyword in n.title.lower()
        ]
        if not matches:
            out.append(
                f"- {label}: named in the issue but absent from this graph — "
                "cannot confirm from the graph alone.\n",
            )
            continue
        for node in matches:
            if node.uid in implemented:
                out.append(
                    f"- {label}: `{_cell(_concept_id(node.uid))}` is present "
                    "and implemented — no gap.\n",
                )
            else:
                out.append(
                    f"- {label}: `{_cell(_concept_id(node.uid))}` is present "
                    "and unimplemented — confirmed gap.\n",
                )
    return "".join(out)


def _subgraph_for_concept(graph: CorpusGraph, concept_id: str) -> CorpusGraph:
    """The 1-hop neighbourhood of one concept, as its own graph.

    Why 1-hop: the single-concept render is a subset view of the same six
    indices, so it keeps the concept plus every node an edge touches from
    it (definitions, documents, implementing repos) and the edges between
    the kept nodes — nothing else.
    """
    uid = (
        concept_id
        if concept_id.startswith("concept:")
        else f"concept:{concept_id}"
    )
    node = graph.get_node(uid)
    if node is None:
        raise ValueError(f"concept '{concept_id}' not found")
    keep_uids = {uid}
    for edge in graph.edges:
        if uid in (edge.source, edge.target):
            keep_uids.add(edge.source)
            keep_uids.add(edge.target)
    sub = CorpusGraph()
    for kept_uid in sorted(keep_uids):
        kept = graph.get_node(kept_uid)
        if kept is not None:
            sub.add_node(kept)
    for edge in graph.edges:
        if edge.source in keep_uids and edge.target in keep_uids:
            sub.add_edge(edge)
    return sub


def render_all(
    graph: CorpusGraph, concept: str | None = None,
) -> dict[str, str]:
    """Render all six indices, optionally restricted to one concept.

    Raises ValueError when ``concept`` names no concept in the graph.
    """
    target = graph
    if concept is not None:
        target = _subgraph_for_concept(graph, concept)
    return {
        "concept-index.md": render_concept_index(target),
        "provenance-map.md": render_provenance_map(target),
        "spec-coverage.md": render_spec_coverage(target),
        "tag-analysis.md": render_tag_analysis(target),
        "cross-corpus-bridges.md": render_cross_corpus_bridges(target),
        "gaps.md": render_gaps(target),
    }


def render_to_directory(
    graph: CorpusGraph,
    output_dir: Path | str,
    concept: str | None = None,
) -> list[Path]:
    """Write all six indices into ``output_dir``; return the files written."""
    rendered = render_all(graph, concept=concept)
    out_dir = Path(output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for name in RENDER_FILES:
        path = out_dir / name
        path.write_text(rendered[name], encoding="utf-8")
        written.append(path)
    return written
